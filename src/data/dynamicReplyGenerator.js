/**
 * Generates a rich, unique, randomized draft tailored strictly around the petition
 * Guaranteed NO @ mentions
 */
export function generateUniqueReply(angleId = null) {
  const angle = angleId 
    ? GRIEVANCE_ANGLES.find(a => a.id === angleId) || GRIEVANCE_ANGLES[0]
    : GRIEVANCE_ANGLES[Math.floor(Math.random() * GRIEVANCE_ANGLES.length)];

  const hook = angle.hooks[Math.floor(Math.random() * angle.hooks.length)];
  const body = angle.bodies[Math.floor(Math.random() * angle.bodies.length)];
  const demand = angle.demands[Math.floor(Math.random() * angle.demands.length)];

  // Personalization prompt insertion
  const personalPointers = [
    '(Mention your rank / GMR here)',
    '(Add 1 line on your dream branch / college like JU/CU/KGEC)',
    '(Share how multiple allocations affected your seat)',
    '(Add your personal experience with Phase 1/2 results)'
  ];
  const pointer = personalPointers[Math.floor(Math.random() * personalPointers.length)];

  const fullText = `${hook}\n\n${body}\n\n👉 ${pointer}: [Add your custom sentence here]\n\n${demand}\n\n${angle.hashtags}`;

  return {
    angleId: angle.id,
    angleTitle: angle.name,
    angleSummary: angle.summary,
    text: fullText,
    charCount: fullText.length
  };
}

/**
 * Checks if the user has modified/personalized the template text
 * Enforces anti-bot mandatory editing rule
 */
export function checkTextCustomized(originalText, currentText) {
  if (!currentText || currentText.trim().length < 40) {
    return {
      isValid: false,
      reason: 'Draft is too short. Please write your genuine concern.'
    };
  }

  // Check if user removed the placeholder pointer or changed significant text
  const hasUneditedPlaceholder = currentText.includes('[Add your custom sentence here]') ||
                                currentText.includes('(Mention your rank') ||
                                currentText.includes('(Add 1 line on your dream') ||
                                currentText.includes('(Share how multiple allocations');

  if (hasUneditedPlaceholder) {
    return {
      isValid: false,
      reason: 'Please replace the [Add your custom sentence here] bracket with your own rank, words, or branch to unlock dispatch!'
    };
  }

  // Calculate simple edit distance/difference
  const isIdentical = originalText.trim() === currentText.trim();
  if (isIdentical) {
    return {
      isValid: false,
      reason: 'Mandatory Customization: Please modify or tweak a few words in your own voice to prevent X from flagging your account.'
    };
  }

  return {
    isValid: true,
    reason: 'Personalization Active! Ready to dispatch reply.'
  };
}
